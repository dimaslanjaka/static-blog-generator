"""
Delete `node_modules` directories recursively from a workspace root,
but only if a `package.json` exists at that workspace root.

Usage:
  python clean_workspaces_node_modules.py              # dry run
  python clean_workspaces_node_modules.py --force     # actually delete
  python clean_workspaces_node_modules.py C:\\path\\to\\workspace --force
"""

import argparse
import glob
import json
import os
import shutil
from pathlib import Path


def delete_lockfiles(root: Path, dry_run: bool = True):
    """Delete lock files in the given root directory."""
    lock_files = [
        "yarn.lock",
        "package-lock.json",
        "pnpm-lock.yaml",
        "npm-shrinkwrap.json",
    ]

    for lock in lock_files:
        lf = root / lock

        if lf.exists():
            if dry_run:
                print(f"[DRY RUN] Deleting lock file: {lf}")
            else:
                print(f"Deleting lock file: {lf}")
                lf.unlink()
        else:
            if dry_run:
                print(f"[SKIP]   No {lock} at: {root}")


def collect_workspace_dirs(start_root: Path):
    """
    Return all workspace package directories recursively based on
    `workspaces` declarations in package.json files.
    """
    visited = set()
    results = set()
    stack = [start_root.resolve()]

    while stack:
        pkg_dir = stack.pop()

        if pkg_dir in visited:
            continue

        visited.add(pkg_dir)

        pkg_file = pkg_dir / "package.json"

        if not pkg_file.is_file():
            continue

        results.add(pkg_dir)

        try:
            data = json.loads(pkg_file.read_text(encoding="utf-8"))
        except Exception:
            continue

        workspaces = data.get("workspaces")
        patterns = []

        if isinstance(workspaces, dict):
            patterns = workspaces.get("packages", [])
        elif isinstance(workspaces, list):
            patterns = workspaces

        for pattern in patterns:
            matches = glob.glob(str(pkg_dir / pattern), recursive=True)

            for match in matches:
                path = Path(match)

                if path.is_symlink():
                    continue

                resolved = path.resolve()

                if resolved.is_dir() and resolved not in visited:
                    stack.append(resolved)

    return results


def delete_node_modules(root: Path, dry_run: bool = True):
    """
    Delete node_modules only for workspace package folders.
    """
    workspace_dirs = collect_workspace_dirs(root)

    for pkg_dir in sorted(workspace_dirs):
        node_modules = pkg_dir / "node_modules"

        if node_modules.exists():
            if dry_run:
                print(f"[DRY RUN] Deleting node_modules at: {node_modules}")
            else:
                print(f"Deleting node_modules at: {node_modules}")
                shutil.rmtree(node_modules, ignore_errors=True)
        else:
            if dry_run:
                print(f"[SKIP]   No node_modules at: {pkg_dir}")

        delete_lockfiles(pkg_dir, dry_run=dry_run)


def main():
    parser = argparse.ArgumentParser(
        description="Recursively remove node_modules only inside valid workspaces"
    )

    parser.add_argument(
        "path",
        nargs="?",
        default=str(Path.cwd()),
        help=f"Workspace root (default: {Path.cwd()})",
    )

    parser.add_argument(
        "-f",
        "--force",
        action="store_true",
        help="Actually delete files/directories",
    )

    args = parser.parse_args()

    root_path = Path(args.path).resolve()

    if not root_path.is_dir():
        print(f"Error: '{root_path}' is not a directory")
        raise SystemExit(1)

    package_json = root_path / "package.json"

    if not package_json.is_file():
        print(
            f"Refusing to operate: no package.json found at workspace root '{root_path}'"
        )
        raise SystemExit(2)

    dry_run = not args.force

    if dry_run:
        print("Dry run mode (no deletions). Add --force to delete.\n")

    delete_node_modules(root_path, dry_run=dry_run)


if __name__ == "__main__":
    main()
